package git

import "testing"

// Every git action says so when git itself fails: outside a repository
// (or on a ref that does not exist) the answer is an error, never a
// silent empty result.
func TestActionsOutsideARepoReturnErrors(t *testing.T) {
	d := t.TempDir()
	opt := RebaseOptions{}
	calls := map[string]func() error{
		"RestackAgentWorktree":   func() error { _, e := RestackAgentWorktree(d, "x", AgentRestackOptions{}); return e },
		"CommitAgentWorktreeAs":  func() error { _, e := CommitAgentWorktreeAs(d, "x", "m", ""); return e },
		"AgentChanges":           func() error { _, e := AgentChanges(d, "x"); return e },
		"MergeAgentWorktree":     func() error { _, e := MergeAgentWorktree(d, "x", false); return e },
		"RemoveAgentWorktree":    func() error { return RemoveAgentWorktree(d, "x", true) },
		"LeftoverAgentWorktrees": func() error { _, e := LeftoverAgentWorktrees(d); return e },
		"AgentNumstat":           func() error { _, e := AgentNumstat(d, "x"); return e },
		"BaseDiffFiles":          func() error { _, _, e := BaseDiffFiles(d, "main"); return e },
		"BisectStart":            func() error { _, e := BisectStart(d, "a", "b"); return e },
		"BisectMark":             func() error { _, e := BisectMark(d, "good"); return e },
		"BisectRun":              func() error { _, e := BisectRun(d, d, "true"); return e },
		"RefNames":               func() error { _, e := RefNames(d); return e },
		"MergeBase":              func() error { _, e := MergeBase(d, "a", "b"); return e },
		"WorkTreeDiffFiles":      func() error { _, e := WorkTreeDiffFiles(d, "HEAD"); return e },
		"BlameFile":              func() error { _, e := BlameFile(d, "a", BlameOptions{}); return e },
		"LineHistory":            func() error { _, e := LineHistory(d, "a", 1, 2); return e },
		"DeleteRemoteBranch":     func() error { return DeleteRemoteBranch(d, "origin/x") },
		"BranchList":             func() error { _, e := BranchList(d); return e },
		"CheckoutTracking":       func() error { return CheckoutTracking(d, "origin/x") },
		"StashAndSwitch":         func() error { return StashAndSwitch(d, "x") },
		"UnstageAll":             func() error { return UnstageAll(d) },
		"DeleteUntracked":        func() error { _, e := DeleteUntracked(d); return e },
		"CommitAll":              func() error { return CommitAll(d, "m") },
		"StagedFiles":            func() error { _, e := StagedFiles(d); return e },
		"StagedAddedLines":       func() error { _, e := StagedAddedLines(d); return e },
		"CommitFiles":            func() error { _, e := CommitFiles(d, "HEAD"); return e },
		"ChangesDiff":            func() error { _, _, e := ChangesDiff(d, true, 100); return e },
		"MarkResolved":           func() error { return MarkResolved(d, "a") },
		"ResolveWithSide":        func() error { return ResolveWithSide(d, "a", "ours") },
		"ReadConflictStages":     func() error { _, e := ReadConflictStages(d, "a"); return e },
		"ShowCapped":             func() error { _, _, _, e := ShowCapped(d, "HEAD", 100); return e },
		"GetBranch":              func() error { _, e := GetBranch(d); return e },
		"FileHistory":            func() error { _, e := FileHistory(d, "a", 3); return e },
		"Log":                    func() error { _, e := Log(d, 3); return e },
		"GraphLog":               func() error { _, e := GraphLog(d, 3); return e },
		"StashList":              func() error { _, e := StashList(d); return e },
		"PeekHunk":               func() error { _, e := PeekHunk(d, "a", 1); return e },
		"AddIgnore":              func() error { return AddIgnore(d+"/nodir/x", "*.o") },
		"RefreshIndex":           func() error { return RefreshIndex(d) },
		"CommitPaths":            func() error { return CommitPaths(d, "m", []string{"a"}, CommitOptions{}) },
		"Contributors":           func() error { _, e := Contributors(d); return e },
		"Unshallow":              func() error { return Unshallow(d) },
		"StagedCRLF":             func() error { _, e := StagedCRLF(d); return e },
		"LFSFiles":               func() error { _, e := LFSFiles(d); return e },
		"UnstageLines":           func() error { return UnstageLines(d, "a", 1, 2) },
		"TrackedFiles":           func() error { _, e := TrackedFiles(d); return e },
		"OpContinue":             func() error { return OpContinue(d, "merge") },
		"OpAbort":                func() error { return OpAbort(d, "merge") },
		"LastCommitForMove":      func() error { _, e := LastCommitForMove(d); return e },
		"MoveLastCommit":         func() error { return MoveLastCommit(d, "abc", "x", true, false) },
		"RemoteWeb":              func() error { _, e := RemoteWeb(d); return e },
		"BranchOnlyCommits":      func() error { _, e := BranchOnlyCommits(d, "x", 0); return e },
		"CommitsNotOn":           func() error { _, e := CommitsNotOn(d, "x", 0); return e },
		"CherryPickMany":         func() error { _, e := CherryPickMany(d, []string{"abc"}); return e },
		"MergeParents":           func() error { _, e := MergeParents(d, "abc"); return e },
		"ApplyFileFromCommit":    func() error { return ApplyFileFromCommit(d, "abc", "a") },
		"RestoreFileFrom":        func() error { _, e := RestoreFileFrom(d, "abc", "a"); return e },
		"RebaseOnto":             func() error { _, e := RebaseOnto(d, "main", false, opt); return e },
		"ResolveCommitName":      func() error { _, e := ResolveCommitName(d, "main"); return e },
		"RewordCommit":           func() error { _, e := RewordCommit(d, "abc", "m", opt); return e },
		"DropCommit":             func() error { _, e := DropCommit(d, "abc", opt); return e },
		"SquashIntoPrevious":     func() error { _, e := SquashIntoPrevious(d, "abc", opt); return e },
		"Autosquash":             func() error { _, e := Autosquash(d, opt); return e },
		"CommitPatch":            func() error { _, e := CommitPatch(d, "abc"); return e },
		"CheckPatch":             func() error { _, e := CheckPatch(d, "x"); return e },
		"OutgoingFiles":          func() error { _, e := OutgoingFiles(d, "main"); return e },
		"PushTo":                 func() error { return PushTo(d, "origin", "main") },
		"PullFrom":               func() error { return PullFrom(d, "origin", "main", true) },
		"FetchAll":               func() error { return FetchAll(d) },
		"RemoteNames":            func() error { _, e := RemoteNames(d); return e },
		"LoadRebaseTodo":         func() error { _, e := LoadRebaseTodo(d, "main"); return e },
		"FixupInto":              func() error { _, e := FixupInto(d, "abc", opt); return e },
		"RebaseContinue":         func() error { _, e := RebaseContinue(d, opt); return e },
		"WorkDiff":               func() error { _, _, e := WorkDiff(d, 10); return e },
		"BranchDiff":             func() error { _, _, e := BranchDiff(d, "main", 10); return e },
		"SetSigning":             func() error { return SetSigning(d, true) },
		"StashPush":              func() error { return StashPush(d, StashOptions{}) },
		"StashDiff":              func() error { _, e := StashDiff(d, "stash@{0}"); return e },
		"ResetHardSafe":          func() error { _, e := ResetHardSafe(d, "HEAD"); return e },
		"CreateTag":              func() error { return CreateTag(d, "t", "HEAD", "") },
		"TagDetail":              func() error { _, e := TagDetail(d, "t"); return e },
		"ListRemotes":            func() error { _, e := ListRemotes(d); return e },
		"PlanUndo":               func() error { _, e := PlanUndo(d); return e },
		"RunUndo":                func() error { _, e := RunUndo(d, UndoPlan{Target: "abc"}, UndoOptions{}); return e },
		"AddWorktree":            func() error { return AddWorktree(d, d+"/w", "b", "") },
		"WorktreeRefs":           func() error { _, _, e := WorktreeRefs(d); return e },
		"ForgetWorktree":         func() error { return ForgetWorktree(d, d+"/w") },
		"RemoveWorktree":         func() error { return RemoveWorktree(d, d+"/w", true) },
		"RestoreWorktree":        func() error { return RestoreWorktree(d, d+"/w", "b") },
		"ListWorktrees":          func() error { _, _, e := ListWorktrees(d); return e },
		"BranchUnmerged":         func() error { _, e := BranchUnmerged(d, "x", "main"); return e },
	}
	for name, fn := range calls {
		if err := fn(); err == nil {
			t.Errorf("%s outside a repository: want an error", name)
		}
	}
}
