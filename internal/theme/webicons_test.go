package theme

import (
	"fmt"
	"os"
	"sort"
	"strings"
	"testing"
)

// The web workbench draws the same file icons as the TUI: the table in
// internal/webgw/assets/src/lib/fileicons.ts is this package's table,
// written out (UPDATE_WEB_ICONS=1 go test -run TestWebFileIcons ./internal/theme
// rewrites it). Each colour is the token of the same name in the page
// (the workbench maps them to the icon theme's own colours).

const webIconsPath = "../webgw/assets/src/lib/fileicons.ts"

func webIconToken(c *Color256) string {
	switch c {
	case &AccentBlue:
		return "blue"
	case &AccentAmber:
		return "yellow"
	case &AccentGreen:
		return "green"
	case &AccentRedCoral:
		return "red"
	case &AccentMagenta:
		return "pink"
	case &AccentLavender:
		return "purple"
	case &TextSecondary:
		return "white"
	default:
		return "grey"
	}
}

func webIconRow(key string, d fileIconDef) string {
	return fmt.Sprintf("  [%q, %q, %q],\n", key, d.nerd, webIconToken(d.color))
}

func webIconsTS() string {
	var b strings.Builder
	b.WriteString("// Code generated by UPDATE_WEB_ICONS=1 go test -run TestWebFileIcons ./internal/theme; DO NOT EDIT.\n")
	b.WriteString("// The TUI's file icons (internal/theme/fileicons.go): [key, glyph, colour].\n\n")
	b.WriteString("export type IconRow = readonly [string, string, string];\n\n")
	keys := func(m map[string]fileIconDef) []string {
		out := make([]string, 0, len(m))
		for k := range m {
			out = append(out, k)
		}
		sort.Strings(out)
		return out
	}
	b.WriteString("export const BY_NAME: readonly IconRow[] = [\n")
	for _, k := range keys(fileIconsByName) {
		b.WriteString(webIconRow(k, fileIconsByName[k]))
	}
	b.WriteString("];\n\nexport const BY_PREFIX: readonly IconRow[] = [\n")
	for _, p := range fileIconsByPrefix {
		b.WriteString(webIconRow(p.prefix, p.def))
	}
	b.WriteString("];\n\nexport const BY_EXT: readonly IconRow[] = [\n")
	for _, k := range keys(fileIconsByExt) {
		b.WriteString(webIconRow(k, fileIconsByExt[k]))
	}
	b.WriteString("];\n\n")
	b.WriteString(fmt.Sprintf("export const FILE: IconRow = [\"\", %q, %q];\n", fileIconDefault.nerd, webIconToken(fileIconDefault.color)))
	b.WriteString(fmt.Sprintf("export const DIR: IconRow = [\"\", %q, %q];\n", dirClosedIcon.nerd, webIconToken(dirClosedIcon.color)))
	b.WriteString(fmt.Sprintf("export const DIR_OPEN: IconRow = [\"\", %q, %q];\n", dirOpenIcon.nerd, webIconToken(dirOpenIcon.color)))
	return b.String()
}

func TestWebFileIconsMatchTheTUI(t *testing.T) {
	want := webIconsTS()
	if os.Getenv("UPDATE_WEB_ICONS") == "1" {
		if err := os.WriteFile(webIconsPath, []byte(want), 0o644); err != nil {
			t.Fatal(err)
		}
	}
	got, err := os.ReadFile(webIconsPath)
	if err != nil {
		t.Fatalf("%v (UPDATE_WEB_ICONS=1 writes it)", err)
	}
	if string(got) != want {
		t.Fatalf("%s is not the TUI's icon table; run UPDATE_WEB_ICONS=1 go test -run TestWebFileIcons ./internal/theme", webIconsPath)
	}
}
