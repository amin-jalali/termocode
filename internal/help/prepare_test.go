func TestPrepareConstructs(t *testing.T) {
	cases := []struct{ name, in, want string }{
		{"front matter", "---\ntitle: x\nhide:\n  - toc\n---\n\n# Hi\n", "\n# Hi\n"},
		{"no front matter", "# Hi\n\n---\n\nText\n", "# Hi\n\n---\n\nText\n"},
		{"banner", "<!-- Generated by `go run ./cmd/docgen` — do not edit by hand. -->\n\n# Keys\n", "\n# Keys\n"},
		{"admonition with title", "!!! tip \"Small models\"\n    Use a small one.\n    Really.\n\nAfter.\n",
			"> **Tip — Small models**\n>\n> Use a small one.\n> Really.\n\nAfter.\n"},
		{"admonition without title", "!!! warning\n    Careful.\n", "> **Warning**\n>\n> Careful.\n"},
		{"admonition empty title", "!!! note \"\"\n    Body.\n", "> **Note**\n>\n> Body.\n"},
		{"details", "??? note \"More\"\n    Hidden.\n", "> **Note — More**\n>\n> Hidden.\n"},
		{"details open", "???+ info \"More\"\n    Shown.\n", "> **Info — More**\n>\n> Shown.\n"},
		{"admonition blank line inside", "!!! tip\n    One.\n\n    Two.\nOut.\n", "> **Tip**\n>\n> One.\n>\n> Two.\n\nOut.\n"},
		{"admonition in list", "1. Step\n\n    !!! tip\n        Inner.\n", "1. Step\n\n    > **Tip**\n    >\n    > Inner.\n"},
		{"admonition with code fence", "!!! tip\n    ```sh\n    !!! not one\n    ```\n", "> **Tip**\n>\n> ```sh\n> !!! not one\n> ```\n"},
		{"nested admonition", "!!! note\n    !!! tip \"In\"\n        Deep.\n", "> **Note**\n>\n> > **Tip — In**\n> >\n> > Deep.\n"},
		{"button attrs", "[Get Started](getting-started/install.md){ .md-button .md-button--primary }\n",
			"[Get Started](getting-started/install.md)\n"},
		{"image attrs", "![shot](a.gif){ .tc-shot }\n", "![shot](a.gif)\n"},
		{"id attrs", "Text {: #here }\n", "Text\n"},
		{"icon and lg", "-   :material-robot-outline:{ .lg } **AI Agents.**\n", "- **AI Agents.**\n"},
		{"octicon in link", "[:octicons-arrow-right-24: Customize](guides/customize.md) · [Ext](extensions.md)\n",
			"[Customize](guides/customize.md) · [Ext](extensions.md)\n"},
		{"code span kept", "Use `{ .x }` and `:material-x:` here.  \n", "Use `{ .x }` and `:material-x:` here.  \n"},
		{"div wrappers", "<div class=\"grid cards\" markdown>\n\n- a\n\n</div>\n", "\n\n- a\n\n\n"},
		{"stats", "<div markdown><strong>&lt; 70 ms</strong><span>start to a usable window</span></div>\n",
			"- **< 70 ms** start to a usable window\n"},
		{"p tag", "<p class=\"tc-lead\">A full-featured IDE.</p>\n", "A full-featured IDE.\n"},
		{"small tag", "<small>early release</small>\n", "early release\n"},
		{"keys", "Press ++ctrl+p++ now.\n", "Press `Ctrl+P` now.\n"},
		{"tabs", "=== \"Linux\"\n    apt install x\n", "**Linux**\n\napt install x\n"},
		{"fence untouched", "```json title=\"x\"\n{ .a } :material-x: <div>\n```\n", "```json title=\"x\"\n{ .a } :material-x: <div>\n```\n"},
		{"tilde fence untouched", "~~~\n!!! tip\n~~~\n", "~~~\n!!! tip\n~~~\n"},
		{"control bytes", "a\x1b[31mb\x07c\u0085d\r\n", "a[31mbcd\n"},
		{"no newline at end", "!!! tip\n    x", "> **Tip**\n>\n> x"},
	}
	for _, c := range cases {
		if got := Prepare(c.in); got != c.want {
			t.Errorf("%s:\n got %q\nwant %q", c.name, got, c.want)
		}
	}
}

// No site-only syntax survives on any embedded page.
func TestPrepareEveryPage(t *testing.T) {
	n := 0
	err := fs.WalkDir(docs.FS, ".", func(p string, d fs.DirEntry, err error) error {
		if err != nil || d.IsDir() {
			return err
		}
		n++
		b, err := fs.ReadFile(docs.FS, p)
		if err != nil {
			return err
		}
		out := Prepare(string(b))
		for _, bad := range []string{"!!!", "??? ", "{ .", "{: ", ":material-", ":octicons-", ":fontawesome-", "<div", "</div", "<p ", "<strong", "<!-- Generated", "\x1b"} {
			if strings.Contains(out, bad) {
				t.Errorf("%s: %q survives Prepare", p, bad)
			}
		}
		if strings.HasPrefix(out, "---\n") {
			t.Errorf("%s: front matter survives", p)
		}
		return nil
	})
	if err != nil {
		t.Fatal(err)
	}
	if n < 20 {
		t.Fatalf("only %d embedded pages", n)
	}
	p, err := Load("guides/ai-setup.md")
	if err != nil {
		t.Fatal(err)
	}
	if !strings.Contains(p.Source, "> **Tip — Small models for ghost text**") {
		t.Errorf("admonition not turned into a titled quote")
	}
}
