/** StringKey is a key of the page's strings or of the workbench's
 * (strings.desk.ts, in workbench.js). */
export type StringKey = keyof typeof S | keyof typeof SD;

const desk = dict<string>();

/** addStrings adds the workbench's strings (strings.desk.ts) once
 * workbench.js loads. */
export function addStrings(d: Readonly<Record<string, string>>): void {
  for (const k of Object.keys(d)) desk[k] = d[k];
}

const page: Readonly<Record<string, string>> = S;

export type Lang = "en" | "fa";

/** lang is the language of the UI. t() reads it, so every view that
 * shows a string draws again when it changes. main.tsx sets it to "fa"
 * only once the Persian strings are loaded. */
export const lang = signal<Lang>("en");

/** persian holds the Persian strings (strings.fa.ts) once loaded: they
 * are their own file, strings-fa.js (lib/lazy.ts loads it), so the
 * phone's first files carry English only. */
export const persian = signal<Readonly<Partial<Record<StringKey, string>>> | null>(null);

const FA_DIGITS = "۰۱۲۳۴۵۶۷۸۹";

/** localDigits writes a number of a sentence in the UI language: Persian
 * digits in Persian text. Data (counts in the strip, paths, code, line
 * numbers) never goes through it and keeps Latin digits (WEB-UX-5). */
export function localDigits(v: number, l: Lang): string {
  const s = String(v);
  return l === "fa" ? s.replace(/[0-9]/g, (d) => FA_DIGITS[Number(d)]) : s;
}

/** t returns the text of key in the UI language (English when the
 * Persian text is missing) with each {name} replaced by vars[name].
 * Number values follow the language's digits; text values are data and
 * stay as they are. */
export function t(key: StringKey, vars?: Record<string, string | number>): string {
  const l = lang.value;
  const fa = l === "fa" ? persian.value : null;
  const text: string = (fa && fa[key]) || (has(page, key) ? page[key] : desk[key]) || key;
  if (!vars) return text;
  return text.replace(/\{([a-z_]+)\}/g, (m, name: string) => {
    if (!has(vars, name)) return m;
    const v = vars[name];
    return typeof v === "number" ? localDigits(v, l) : v;
  });
}

type Plural = "pill.cards" | "edit.sent" | "git.commit" | "git.commit_confirm" | "e.idle" | "e.max" | "gg.files" | "im.models_n" | "im.tools_n";

/** tn picks the .one or .other form of a plural key by n. */
export function tn(key: Plural, n: number, vars?: Record<string, string | number>): string {
  return t(n === 1 ? `${key}.one` : `${key}.other`, { n, ...vars });
}
