package manifest

import (
	"fmt"
	"path"
	"sort"
	"strconv"
	"strings"
)

// LockFile is the name of the lock cmd/webbuild writes next to the assets.
const LockFile = "assets.lock"

// LockEntry is one built file: its path under the assets folder, its SRI
// value and its size in bytes.
type LockEntry struct {
	Path string
	SRI  string
	Size int
}

const lockHeader = "# Code generated by go generate ./internal/webgw/assets; DO NOT EDIT.\n" +
	"# One built file per line: path, sha384 (SRI form), size in bytes.\n"

// FormatLock writes the lock for files, sorted by path.
func FormatLock(files map[string][]byte) string {
	names := make([]string, 0, len(files))
	for n := range files {
		names = append(names, n)
	}
	sort.Strings(names)
	var b strings.Builder
	b.WriteString(lockHeader)
	for _, n := range names {
		fmt.Fprintf(&b, "%s %s %d\n", n, SRI(files[n]), len(files[n]))
	}
	return b.String()
}

// ParseLock reads a lock. Comment and blank lines are skipped; every other
// line must be "path sha384-… size" with a clean relative path, once.
func ParseLock(text string) ([]LockEntry, error) {
	var out []LockEntry
	seen := map[string]bool{}
	for i, line := range strings.Split(text, "\n") {
		if line == "" || strings.HasPrefix(line, "#") {
			continue
		}
		f := strings.Fields(line)
		if len(f) != 3 {
			return nil, fmt.Errorf("%s:%d: want path, sha384 and size", LockFile, i+1)
		}
		size, err := strconv.Atoi(f[2])
		if err != nil || size < 0 {
			return nil, fmt.Errorf("%s:%d: bad size %q", LockFile, i+1, f[2])
		}
		if !strings.HasPrefix(f[1], "sha384-") {
			return nil, fmt.Errorf("%s:%d: %q is not a sha384 SRI value", LockFile, i+1, f[1])
		}
		p := f[0]
		if path.Clean(p) != p || strings.HasPrefix(p, "../") || strings.HasPrefix(p, "/") || p == ".." {
			return nil, fmt.Errorf("%s:%d: bad path %q", LockFile, i+1, p)
		}
		if seen[p] {
			return nil, fmt.Errorf("%s:%d: %s listed twice", LockFile, i+1, p)
		}
		seen[p] = true
		out = append(out, LockEntry{Path: p, SRI: f[1], Size: size})
	}
	return out, nil
}
