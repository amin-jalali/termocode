package webproto

//go:generate go run ./gen

import (
	"bytes"
	"encoding/json"
	"fmt"
	"reflect"
	"sort"
	"strings"
)

// The generator turns the Go types and the op table into proto.d.ts (the
// browser's TypeScript types) and schema.json (a JSON Schema the browser
// store checks deltas against, plus the op table). Both files are
// committed; TestProtoTSInSync fails when they are stale.

var (
	rawType  = reflect.TypeOf(json.RawMessage(nil))
	roleType = reflect.TypeOf(Role(""))
	codeType = reflect.TypeOf(ErrCode(""))
	closeTyp = reflect.TypeOf(CloseCode(0))
)

// browserRoles are the roles a browser can have (RoleCtl is never one).
var browserRoles = []Role{RoleViewer, RoleController}

type genType struct {
	t      reflect.Type
	strict bool // decoded strictly (browser → hub); else tolerant
}

// genTypes walks every message and args type, in a stable order: client,
// server and gateway messages by kind, then args in table order; nested
// structs follow the first type that uses them.
func genTypes(browserOnly bool) []genType {
	var out []genType
	seen := map[reflect.Type]bool{}
	var add func(t reflect.Type, strict bool)
	add = func(t reflect.Type, strict bool) {
		for t.Kind() == reflect.Pointer || t.Kind() == reflect.Slice || t.Kind() == reflect.Map {
			t = t.Elem()
		}
		if t.Kind() != reflect.Struct || seen[t] {
			return
		}
		seen[t] = true
		out = append(out, genType{t, strict})
		for i := 0; i < t.NumField(); i++ {
			add(t.Field(i).Type, strict)
		}
	}
	for _, k := range ClientKinds() {
		add(reflect.TypeOf(clientKinds[k]()), true)
	}
	for _, k := range ServerKinds() {
		add(reflect.TypeOf(serverKinds[k]()), false)
	}
	if !browserOnly {
		for _, k := range GatewayKinds() {
			add(reflect.TypeOf(gatewayKinds[k]()), true)
		}
	}
	for _, p := range opTable {
		if browserOnly && p.Role == RoleCtl {
			continue
		}
		add(reflect.TypeOf(p.New()), true)
	}
	for _, d := range topicDataList() { // topicdata.go: hub → browser, tolerant
		add(d.Snap, false)
		add(d.Delta, false)
	}
	for _, k := range EventKinds() {
		add(eventData[k], false)
	}
	for _, p := range opTable {
		if r, ok := resultData[p.Op]; ok && !(browserOnly && p.Role == RoleCtl) {
			add(r, false)
		}
	}
	return out
}

type jsonField struct {
	name     string
	optional bool
	f        reflect.StructField
}

// enumOf is a string field's allowed values from its `enum:"a|b"` tag.
func enumOf(f reflect.StructField) []string {
	tag := f.Tag.Get("enum")
	if tag == "" || f.Type.Kind() != reflect.String {
		return nil
	}
	return strings.Split(tag, "|")
}

// fieldTS is a field's TypeScript type: an enum tag gives a union of
// string literals.
func fieldTS(f reflect.StructField) string {
	if vs := enumOf(f); vs != nil {
		return quoted(vs)
	}
	return tsType(f.Type)
}

// fieldSchema is a field's JSON Schema: an enum tag gives an enum.
func fieldSchema(f reflect.StructField) any {
	if vs := enumOf(f); vs != nil {
		return map[string]any{"enum": vs}
	}
	return schemaOf(f.Type)
}

func jsonFields(t reflect.Type) []jsonField {
	var out []jsonField
	for i := 0; i < t.NumField(); i++ {
		f := t.Field(i)
		tag := f.Tag.Get("json")
		name, opts, _ := strings.Cut(tag, ",")
		if name == "-" || name == "" {
			continue
		}
		opt := strings.Contains(opts, "omitempty") || f.Type.Kind() == reflect.Pointer
		out = append(out, jsonField{name, opt, f})
	}
	return out
}

// kindOf returns the "t" literal of a message type, or "".
func kindOf(t reflect.Type) string {
	if m, ok := reflect.New(t).Interface().(Msg); ok {
		return m.Type()
	}
	return ""
}

func tsType(t reflect.Type) string {
	switch {
	case t == rawType:
		return "unknown"
	case t == roleType:
		return "Role"
	case t == codeType:
		return "ErrCode"
	case t == closeTyp:
		return "CloseCode"
	}
	switch t.Kind() {
	case reflect.Pointer:
		return tsType(t.Elem())
	case reflect.String:
		return "string"
	case reflect.Bool:
		return "boolean"
	case reflect.Int, reflect.Int64, reflect.Uint64, reflect.Uint32, reflect.Int32, reflect.Float64:
		return "number"
	case reflect.Slice:
		return tsType(t.Elem()) + "[]"
	case reflect.Map:
		return "Record<string, " + tsType(t.Elem()) + ">"
	case reflect.Struct:
		return t.Name()
	}
	panic("webproto: no TypeScript type for " + t.String())
}

func quoted[S ~string](vs []S) string {
	q := make([]string, len(vs))
	for i, v := range vs {
		q[i] = fmt.Sprintf("%q", string(v))
	}
	return strings.Join(q, " | ")
}

func unionOf(kinds []string, m map[string]func() Msg) string {
	names := make([]string, len(kinds))
	for i, k := range kinds {
		names[i] = reflect.TypeOf(m[k]()).Elem().Name()
	}
	sort.Strings(names)
	return strings.Join(names, " | ")
}

// GenerateTS returns proto.d.ts: the browser's view of the protocol. Ops
// of the control connection are left out; a browser never sends them.
func GenerateTS() ([]byte, error) {
	var b bytes.Buffer
	b.WriteString("// Code generated by go generate ./internal/webproto; DO NOT EDIT.\n")
	b.WriteString("// Source: internal/webproto (msg.go, args.go, ops.go). See ADR 0020.\n\n")
	fmt.Fprintf(&b, "export type Version = %d;\n", Version)
	fmt.Fprintf(&b, "export type Subprotocol = %q;\n", Subprotocol)
	fmt.Fprintf(&b, "export type Role = %s;\n", quoted(browserRoles))
	fmt.Fprintf(&b, "export type ErrCode = %s;\n", quoted(ErrCodes()))
	codes := make([]string, 0, len(CloseCodes()))
	for _, c := range CloseCodes() {
		codes = append(codes, fmt.Sprint(int(c)))
	}
	fmt.Fprintf(&b, "export type CloseCode = %s;\n", strings.Join(codes, " | "))
	var topics []string
	for _, d := range topicDefs {
		if d.Keyed {
			topics = append(topics, "`"+d.Name+":${number}`")
		} else {
			topics = append(topics, fmt.Sprintf("%q", d.Name))
		}
	}
	fmt.Fprintf(&b, "export type TopicName = %s;\n", strings.Join(topics, " | "))

	for _, g := range genTypes(true) {
		fmt.Fprintf(&b, "\nexport interface %s {\n", g.t.Name())
		kind := kindOf(g.t)
		for _, f := range jsonFields(g.t) {
			if f.name == "t" && kind != "" {
				fmt.Fprintf(&b, "  t: %q;\n", kind)
				continue
			}
			opt := ""
			if f.optional {
				opt = "?"
			}
			fmt.Fprintf(&b, "  %s%s: %s;\n", f.name, opt, fieldTS(f.f))
		}
		b.WriteString("}\n")
	}

	fmt.Fprintf(&b, "\nexport type ClientMsg = %s;\n", unionOf(ClientKinds(), clientKinds))
	fmt.Fprintf(&b, "export type ServerMsg = %s;\n", unionOf(ServerKinds(), serverKinds))
	b.WriteString("\nexport interface OpArgs {\n")
	for _, p := range opTable {
		if p.Role == RoleCtl {
			continue
		}
		fmt.Fprintf(&b, "  %q: %s;\n", p.Op, reflect.TypeOf(p.New()).Elem().Name())
	}
	b.WriteString("}\n\nexport type OpName = keyof OpArgs;\n")
	b.WriteString("\n// The data of a topic's snap and delta messages, by topic name.\nexport interface TopicData {\n")
	for _, d := range topicDataList() {
		fmt.Fprintf(&b, "  %q: { snap: %s; delta: %s };\n", d.Topic, d.Snap.Name(), d.Delta.Name())
	}
	b.WriteString("}\n\n// The data of an ev message, by kind.\nexport interface EventData {\n")
	for _, k := range EventKinds() {
		fmt.Fprintf(&b, "  %q: %s;\n", k, eventData[k].Name())
	}
	b.WriteString("}\n\n// The data of a res message, by op (ops not listed answer without data).\nexport interface OpResult {\n")
	for _, p := range opTable {
		if r, ok := resultData[p.Op]; ok && p.Role != RoleCtl {
			fmt.Fprintf(&b, "  %q: %s;\n", p.Op, r.Name())
		}
	}
	b.WriteString("}\n")
	return b.Bytes(), nil
}

// ---- schema.json ----

type schemaDoc struct {
	Comment     string                       `json:"$comment"`
	Version     int                          `json:"version"`
	Subprotocol string                       `json:"subprotocol"`
	Limits      map[string]int               `json:"limits"`
	CloseCodes  []schemaClose                `json:"close_codes"`
	ErrCodes    []ErrCode                    `json:"err_codes"`
	Topics      []schemaTopic                `json:"topics"`
	Events      map[string]string            `json:"events"`
	Messages    map[string]map[string]string `json:"messages"`
	Ops         []schemaOp                   `json:"ops"`
	Defs        map[string]schemaObj         `json:"defs"`
}

type schemaClose struct {
	Code   CloseCode `json:"code"`
	Reason string    `json:"reason"`
}

type schemaTopic struct {
	Name  string `json:"name"`
	Keyed bool   `json:"keyed"`
	Phase Phase  `json:"phase"`
	Snap  string `json:"snap,omitempty"`  // the def of the snap's data
	Delta string `json:"delta,omitempty"` // the def of a delta's data
}

type schemaOp struct {
	Op          string     `json:"op"`
	Args        string     `json:"args"`
	Result      string     `json:"result,omitempty"` // the def of the res data
	Role        Role       `json:"role"`
	Rate        schemaRate `json:"rate"`
	MaxBytes    int        `json:"max_bytes"`
	BytesPerSec int        `json:"bytes_per_sec,omitempty"`
	Live        int        `json:"live,omitempty"`
	LaptopCard  bool       `json:"laptop_card"`
	Audit       Audit      `json:"audit"`
	Phase       Phase      `json:"phase"`
}

type schemaRate struct {
	N     int   `json:"n"`
	PerMS int64 `json:"per_ms"`
}

type schemaObj struct {
	Type                 string         `json:"type"`
	Properties           map[string]any `json:"properties"`
	Required             []string       `json:"required"`
	AdditionalProperties bool           `json:"additionalProperties"`
}

func schemaOf(t reflect.Type) any {
	switch {
	case t == rawType:
		return map[string]any{}
	case t == roleType:
		return map[string]any{"enum": browserRoles}
	case t == codeType:
		return map[string]any{"enum": ErrCodes()}
	case t == closeTyp:
		return map[string]any{"enum": CloseCodes()}
	}
	switch t.Kind() {
	case reflect.Pointer:
		return schemaOf(t.Elem())
	case reflect.String:
		return map[string]any{"type": "string"}
	case reflect.Bool:
		return map[string]any{"type": "boolean"}
	case reflect.Int, reflect.Int64, reflect.Int32:
		return map[string]any{"type": "integer"}
	case reflect.Uint64, reflect.Uint32:
		return map[string]any{"type": "integer", "minimum": 0}
	case reflect.Float64:
		return map[string]any{"type": "number"}
	case reflect.Slice:
		return map[string]any{"type": "array", "items": schemaOf(t.Elem())}
	case reflect.Map:
		return map[string]any{"type": "object", "additionalProperties": schemaOf(t.Elem())}
	case reflect.Struct:
		return map[string]any{"$ref": "#/defs/" + t.Name()}
	}
	panic("webproto: no schema for " + t.String())
}

func kindTable(kinds []string, m map[string]func() Msg) map[string]string {
	out := map[string]string{}
	for _, k := range kinds {
		out[k] = reflect.TypeOf(m[k]()).Elem().Name()
	}
	return out
}

// GenerateSchema returns schema.json: limits, codes, topics, message and
// op tables and a JSON Schema def per type. Types the hub decodes strictly
// have additionalProperties false; server types allow new fields.
func GenerateSchema() ([]byte, error) {
	doc := schemaDoc{
		Comment:     "Code generated by go generate ./internal/webproto; DO NOT EDIT.",
		Version:     Version,
		Subprotocol: Subprotocol,
		Limits: map[string]int{
			"max_frame": MaxFrame, "max_hello": MaxHello, "max_device_name": MaxDeviceName,
			"max_topics_per_msg": MaxTopicsPerMsg, "max_subscriptions": MaxSubscriptions,
			"max_ping_n": MaxPingN, "max_op_name": MaxOpName,
		},
		ErrCodes: ErrCodes(),
		Messages: map[string]map[string]string{
			"client":  kindTable(ClientKinds(), clientKinds),
			"server":  kindTable(ServerKinds(), serverKinds),
			"gateway": kindTable(GatewayKinds(), gatewayKinds),
		},
		Defs: map[string]schemaObj{},
	}
	for _, c := range CloseCodes() {
		doc.CloseCodes = append(doc.CloseCodes, schemaClose{c, c.Reason()})
	}
	for _, d := range topicDefs {
		st := schemaTopic{Name: d.Name, Keyed: d.Keyed, Phase: d.Phase}
		if td, ok := topicData[d.Name]; ok {
			st.Snap, st.Delta = td.Snap.Name(), td.Delta.Name()
		}
		doc.Topics = append(doc.Topics, st)
	}
	doc.Events = map[string]string{}
	for _, k := range EventKinds() {
		doc.Events[k] = eventData[k].Name()
	}
	for _, p := range opTable {
		res := ""
		if r, ok := resultData[p.Op]; ok {
			res = r.Name()
		}
		doc.Ops = append(doc.Ops, schemaOp{
			Op: p.Op, Args: reflect.TypeOf(p.New()).Elem().Name(), Result: res, Role: p.Role,
			Rate:     schemaRate{N: p.Rate.N, PerMS: p.Rate.Per.Milliseconds()},
			MaxBytes: p.MaxBytes, BytesPerSec: p.BytesPerSec, Live: p.Live,
			LaptopCard: p.LaptopCard, Audit: p.Audit, Phase: p.Phase,
		})
	}
	for _, g := range genTypes(false) {
		obj := schemaObj{Type: "object", Properties: map[string]any{}, Required: []string{},
			AdditionalProperties: !g.strict}
		kind := kindOf(g.t)
		for _, f := range jsonFields(g.t) {
			if f.name == "t" && kind != "" {
				obj.Properties["t"] = map[string]any{"const": kind}
			} else {
				obj.Properties[f.name] = fieldSchema(f.f)
			}
			if !f.optional {
				obj.Required = append(obj.Required, f.name)
			}
		}
		doc.Defs[g.t.Name()] = obj
	}
	var b bytes.Buffer
	enc := json.NewEncoder(&b)
	enc.SetEscapeHTML(false)
	enc.SetIndent("", "  ")
	if err := enc.Encode(doc); err != nil {
		return nil, err
	}
	return b.Bytes(), nil
}
