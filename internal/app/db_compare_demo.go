// databaseCompareDemo shows Compare Schemas without a server (shots and
// goldens): "compare-pick" is the SOURCE picker, "compare" the card on two
// canned PostgreSQL schemas.
func (m *Model) databaseCompareDemo(variant string) tea.Cmd {
	m.databasesDemo("")
	s := m.databases
	stage := dbclient.Conn{ID: "stage-pg", Name: "stage-pg", Driver: "postgres", Host: "stage.internal", Port: 5432}
	s.conns = append(s.conns, stage)
	s.nodes[stage.ID] = dbNode{kind: dbNodeConnection, name: stage.Name, path: stage.ID, conn: stage.ID, detail: "postgres  stage.internal:5432", loaded: true}
	s.touch()
	cs := m.dbCompareS()
	cs.sides = []dbCompareSide{
		{conn: "local-pg", name: "local-pg", sessKey: "local-pg", driver: "postgres", database: "app", schema: "audit"},
		{conn: "local-pg", name: "local-pg", sessKey: "local-pg", driver: "postgres", database: "app", schema: "public"},
		{conn: "stage-pg", name: "stage-pg", sessKey: "stage-pg", driver: "postgres", database: "app", schema: "public"},
	}
	if variant == "compare-pick" {
		return m.onDBCompareSides(dbCompareSidesMsg{gen: cs.gen, sides: cs.sides})
	}
	src, tgt := dbCompareDemoSchemas()
	return m.databaseShowCompare(cs.sides[1].label(), cs.sides[2].label(), dbclient.CompareSchemas(src, tgt))
}

// dbCompareDemoSchemas: the source (local) has a plan column, an orders
// index and a changed view; the target (stage) still has a legacy table.
func dbCompareDemoSchemas() (src, tgt dbclient.CanonSchema) {
	users := func(extra ...dbclient.CanonColumn) dbclient.CanonTable {
		return dbclient.CanonTable{Name: "users", Columns: append([]dbclient.CanonColumn{
			{Name: "id", Type: "bigint", NotNull: true, Extra: "GENERATED BY DEFAULT AS IDENTITY"},
			{Name: "email", Type: "text", NotNull: true},
			{Name: "created_at", Type: "timestamp with time zone", NotNull: true, Default: "now()"},
		}, extra...), Constraints: []dbclient.CanonConstraint{
			{Kind: "PRIMARY KEY", Name: "users_pkey", Columns: []string{"id"}},
			{Kind: "UNIQUE", Name: "users_email_key", Columns: []string{"email"}},
		}}
	}
	orders := dbclient.CanonTable{Name: "orders", Columns: []dbclient.CanonColumn{
		{Name: "id", Type: "bigint", NotNull: true},
		{Name: "user_id", Type: "bigint", NotNull: true},
		{Name: "total", Type: "numeric(12,2)", NotNull: true, Default: "0"},
	}, Constraints: []dbclient.CanonConstraint{
		{Kind: "PRIMARY KEY", Name: "orders_pkey", Columns: []string{"id"}},
		{Kind: "FOREIGN KEY", Name: "orders_user_id_fkey", Columns: []string{"user_id"}, RefTable: "users", RefColumns: []string{"id"}, OnDelete: "CASCADE"},
	}}
	srcOrders := orders
	srcOrders.Indexes = []dbclient.CanonIndex{{Name: "orders_user_id_idx", Exprs: []string{"user_id"}}}
	src = dbclient.CanonSchema{Driver: "postgres", Schema: "public", Label: "local-pg · app · public",
		Tables: []dbclient.CanonTable{users(dbclient.CanonColumn{Name: "plan", Type: "text", NotNull: true, Default: "'free'::text"}), srcOrders},
		Views:  []dbclient.CanonView{{Name: "paying_users", Definition: " SELECT id,\n    email\n   FROM users\n  WHERE plan <> 'free'::text"}},
		Routines: []dbclient.CanonRoutine{{Name: "touch_updated", Kind: "FUNCTION", Returns: "trigger", Language: "plpgsql",
			Body: "\nBEGIN\n  NEW.updated_at := now();\n  RETURN NEW;\nEND;\n"}},
	}
	tgt = dbclient.CanonSchema{Driver: "postgres", Schema: "public", Label: "stage-pg · app · public",
		Tables:   []dbclient.CanonTable{users(), orders, {Name: "legacy_sessions", Columns: []dbclient.CanonColumn{{Name: "token", Type: "text", NotNull: true}, {Name: "user_id", Type: "bigint"}}}},
		Views:    []dbclient.CanonView{{Name: "paying_users", Definition: " SELECT id,\n    email\n   FROM users"}},
		Routines: src.Routines,
	}
	return src, tgt
}
