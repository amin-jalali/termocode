// AI parity guard tables (the shape of ai_db_parity.go): every action
// of the GUI outside the databases, containers / servers / kube and git /
// worktrees pieces maps to the AI tool that does it, or sits on a
// commented not-for-AI list with the reason. TestAIAgentsEveryGUIActionHasAnAITool
// and TestAIRestEveryGUIActionHasAnAITool fail when a palette id the AI
// may never run, or a web op, is on neither list. A palette id that
// execute_action may run (auto or confirm) is the AI's already.
//
// The value of a parity row is the tool (first word, a chat tool) and how
// it does it. A not-for-AI reason says why the AI never gets it: secrets,
// credentials, pairing and approvals stay with the user, the AI never
// changes its own safety settings, and the AI is the chat itself.

