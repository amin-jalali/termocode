// lamAlef maps the alef after a lam to the ligature's isolated form
// (the final form is the next code point).
var lamAlef = map[rune]rune{0x0622: 0xFEF5, 0x0623: 0xFEF7, 0x0625: 0xFEF9, 0x0627: 0xFEFB}

const (
	lam  = 0x0644
	zwnj = 0x200C
	zwj  = 0x200D
	tatw = 0x0640 // tatweel: joins on both sides, has no forms
)

// joinsBefore: the letter connects to the letter before it (all
// joining letters do). joinsAfter: it also connects to the next one.
func joinsBefore(r rune) bool {
	_, ok := forms[r]
	return (ok && r != 0x0621) || r == tatw
}

func joinsAfter(r rune) bool {
	f, ok := forms[r]
	return (ok && f[2] != 0) || r == tatw
}

// Shape returns s with Arabic letters in their presentation forms
// (logical order kept). Joiner controls are dropped.
func Shape(s string) string {
	rs := []rune(s)
	var b []rune
	for _, c := range shapeClusters(rs, nil) {
		b = append(b, []rune(c.text)...)
	}
	return string(b)
}
