//go:build dbint

package dbclient

import (
	"context"
	"os"
	"strings"
	"testing"
	"time"
)

// A live PostgreSQL (TERMOCODE_DBINT_PG_URL): two schemas in one database
// are read on read-only sessions, compared, and the script (run here by
// the test, never by the feature) makes the target match the source.
func TestPostgresCompareSchemasLive(t *testing.T) {
	url := os.Getenv("TERMOCODE_DBINT_PG_URL")
	if url == "" {
		t.Skip("TERMOCODE_DBINT_PG_URL is not set")
	}
	conn, err := ParseURL(url)
	if err != nil {
		t.Fatal(err)
	}
	ctx, cancel := context.WithTimeout(context.Background(), 2*time.Minute)
	defer cancel()
	s, err := NewSQLSession(ctx, conn, conn.Password)
	if err != nil {
		t.Fatal(err)
	}
	defer s.Close()
	run := func(q string) {
		t.Helper()
		if r := s.Run(ctx, q, RunOptions{}); r.Err != nil {
			t.Fatalf("%s: %v", q, r.Err)
		}
	}
	for _, q := range []string{
		`DROP SCHEMA IF EXISTS cmp_src CASCADE`, `DROP SCHEMA IF EXISTS "cmp tgt" CASCADE`,
		`CREATE SCHEMA cmp_src`, `CREATE SCHEMA "cmp tgt"`,
		// source: the model
		`CREATE TABLE cmp_src.users (id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, email text NOT NULL UNIQUE, plan text NOT NULL DEFAULT 'free', "Odd ""Name""" int CHECK ("Odd ""Name""" > 0))`,
		`CREATE TABLE cmp_src.orders (id bigint PRIMARY KEY, user_id bigint REFERENCES cmp_src.users(id) ON DELETE CASCADE, total numeric(12,2) NOT NULL DEFAULT 0)`,
		`CREATE INDEX orders_user_idx ON cmp_src.orders (user_id) WHERE total > 0`,
		`CREATE INDEX users_lower_email ON cmp_src.users (lower(email))`,
		`CREATE VIEW cmp_src.paying AS SELECT id, email FROM cmp_src.users WHERE plan <> 'free'`,
		`CREATE FUNCTION cmp_src.add1(i int) RETURNS int LANGUAGE sql AS 'SELECT i + 1'`,
		// target: what is live
		`CREATE TABLE "cmp tgt".users (id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, email text NOT NULL UNIQUE, "Odd ""Name""" int CHECK ("Odd ""Name""" > 0), age int)`,
		`CREATE TABLE "cmp tgt".legacy (token text)`,
		`CREATE INDEX users_age ON "cmp tgt".users (age)`,
		`CREATE VIEW "cmp tgt".paying AS SELECT id FROM "cmp tgt".users`,
	} {
		run(q)
	}
	defer s.Run(context.Background(), `DROP SCHEMA IF EXISTS cmp_src CASCADE`, RunOptions{})
	defer s.Run(context.Background(), `DROP SCHEMA IF EXISTS "cmp tgt" CASCADE`, RunOptions{})

	read := func(schema string) CanonSchema {
		t.Helper()
		ro, err := s.ReadOnlySession()
		if err != nil {
			t.Fatal(err)
		}
		defer ro.Close()
		out, err := ReadCanonSchema(ctx, ro, "postgres", schema)
		if err != nil {
			t.Fatalf("%s: %v", schema, err)
		}
		return out
	}
	_, schemas, err := ListSchemas(ctx, s, "postgres")
	if err != nil || !strings.Contains(strings.Join(schemas, ","), "cmp tgt") {
		t.Fatalf("schemas %v %v", schemas, err)
	}
	src, tgt := read("cmp_src"), read("cmp tgt")
	files := CanonFiles(src)
	all := ""
	for _, f := range files {
		all += f.Text
	}
	for _, want := range []string{
		`"id" bigint NOT NULL GENERATED BY DEFAULT AS IDENTITY`, `"plan" text NOT NULL DEFAULT 'free'::text`,
		`CONSTRAINT "users_pkey" PRIMARY KEY ("id")`, `CONSTRAINT "users_email_key" UNIQUE ("email")`,
		`CONSTRAINT "users_Odd ""Name""_check" CHECK`, `REFERENCES "users" ("id") ON DELETE CASCADE`,
		`CREATE INDEX "orders_user_idx" ON "orders" (user_id) WHERE total > 0::numeric;`,
		`CREATE INDEX "users_lower_email" ON "users" (lower(email));`,
		`CREATE FUNCTION "add1"(i integer) RETURNS integer LANGUAGE sql AS $$`,
	} {
		if !strings.Contains(all, want) {
			t.Errorf("canonical DDL lacks %q:\n%s", want, all)
		}
	}
	if strings.Contains(all, "cmp_src") {
		t.Errorf("schema name in canonical DDL:\n%s", all)
	}
	cmp := CompareSchemas(src, tgt)
	if cmp.Destructive != 4 { // view, index, column, table
		t.Errorf("destructive = %d:\n%s", cmp.Destructive, cmp.Script)
	}
	// Apply the script (the test does; the feature never runs it).
	for _, stmt := range strings.Split(cmp.Script, ";\n") {
		var lines []string
		for _, l := range strings.Split(stmt, "\n") {
			if !strings.HasPrefix(strings.TrimSpace(l), "--") {
				lines = append(lines, l)
			}
		}
		if q := strings.TrimSpace(strings.Join(lines, "\n")); q != "" {
			run(q)
		}
	}
	after := CompareSchemas(src, read("cmp tgt"))
	// Only the routine is left: the script never writes routines.
	if after.Changes != 1 || after.Destructive != 0 || !strings.Contains(after.Script, `-- REVIEW: function "add1"(i integer) is only in the source`) {
		t.Fatalf("after the script, %d changes:\n%s", after.Changes, after.Script)
	}
	for _, f := range after.Files {
		if f.Name != "routines.sql" && f.Old != f.New {
			t.Errorf("%s still differs:\n%s\n---\n%s", f.Name, f.Old, f.New)
		}
	}
}
