// A PostgreSQL schema read turns every catalog row into the canonical
// model: identity columns, all constraint kinds, non-btree and partial
// indexes, views without the schema name, functions and procedures.
func TestReadCanonSchemaPostgresCatalogRows(t *testing.T) {
	s := &catalogSession{answers: pgCatalog()}
	got, err := ReadCanonSchema(context.Background(), s, "postgresql", "public")
	if err != nil {
		t.Fatal(err)
	}
	if got.Driver != "postgres" || len(got.Tables) != 2 || got.Tables[0].Name != "orders" || got.Tables[1].Name != "users" {
		t.Fatalf("tables: %+v", got)
	}
	orders, users := got.Tables[0], got.Tables[1]
	if users.Columns[0].Extra != "GENERATED ALWAYS AS IDENTITY" || users.Columns[1].Extra != "GENERATED BY DEFAULT AS IDENTITY" || users.Columns[2].Extra != "" {
		t.Errorf("identity: %+v", users.Columns)
	}
	if !users.Columns[0].NotNull || users.Columns[1].NotNull || users.Columns[2].Default != "'x'::text" {
		t.Errorf("not null/default: %+v", users.Columns)
	}
	wantFK := CanonConstraint{Kind: "FOREIGN KEY", Name: "orders_user_fk", Columns: []string{"user_id"}, RefTable: "users", RefColumns: []string{"id"}, OnUpdate: "", OnDelete: "CASCADE"}
	if len(orders.Constraints) != 2 || !reflect.DeepEqual(orders.Constraints[1], wantFK) || orders.Constraints[0].Kind != "PRIMARY KEY" {
		t.Errorf("orders constraints: %+v", orders.Constraints)
	}
	var kinds []string
	for _, c := range users.Constraints {
		kinds = append(kinds, c.Kind)
		if c.Kind == "CHECK" && (c.Check != "CHECK (n > 0)" || c.Columns != nil) {
			t.Errorf("check: %+v", c)
		}
	}
	if strings.Join(kinds, ",") != "UNIQUE,CHECK" {
		t.Errorf("users constraint kinds %v (exclusion constraints must be skipped)", kinds)
	}
	if len(users.Indexes) != 1 || users.Indexes[0].Method != "gin" || users.Indexes[0].Unique {
		t.Errorf("gin index: %+v", users.Indexes)
	}
	oi := orders.Indexes
	if len(oi) != 1 || oi[0].Method != "" || !oi[0].Unique || !reflect.DeepEqual(oi[0].Exprs, []string{"user_id", "id"}) || oi[0].Where != "user_id IS NOT NULL" {
		t.Errorf("btree partial index: %+v", oi)
	}
	if len(got.Views) != 2 {
		t.Fatalf("views: %+v", got.Views)
	}
	if v := got.Views[0]; v.Name != "active" || v.Materialized || strings.Contains(v.Definition, "public") || strings.HasSuffix(v.Definition, ";") {
		t.Errorf("view keeps the schema name or the semicolon: %q", v.Definition)
	}
	if v := got.Views[1]; !v.Materialized || strings.Contains(v.Definition, "public.") {
		t.Errorf("materialized view: %+v", v)
	}
	if len(got.Routines) != 2 || got.Routines[0].Kind != "FUNCTION" || got.Routines[1].Kind != "PROCEDURE" {
		t.Fatalf("routines: %+v", got.Routines)
	}
	if r := got.Routines[0]; r.Args != "x integer" || r.Returns != "integer" || r.Language != "sql" {
		t.Errorf("function: %+v", r)
	}
	if b := got.Routines[1].Body; !strings.Contains(b, "    DELETE FROM orders;") {
		t.Errorf("tab in the body is not four spaces: %q", b)
	}
}

// Any failing catalog read stops the read with the server's error, so
// the compare never shows half a schema as the whole.
func TestReadCanonSchemaStopsOnCatalogError(t *testing.T) {
	cases := map[string][]string{
		"postgres": {"pg_attribute a ON a.attrelid = c.oid", "pg_get_constraintdef", "FROM pg_index ix", "pg_get_viewdef", "FROM pg_proc p"},
		"mysql":    {"information_schema.columns", "information_schema.table_constraints tc\nJOIN", "information_schema.statistics", "information_schema.views", "information_schema.routines", "information_schema.parameters"},
		"sqlite":   {"pragma_table_info", "pragma_index_list", "type = 'index'", "pragma_foreign_key_list", "type = 'view'"},
	}
	for driver, reads := range cases {
		for _, read := range reads {
			s := &catalogSession{answers: pgCatalog(), failOn: read}
			_, err := ReadCanonSchema(context.Background(), s, driver, "app")
			if err == nil || !strings.Contains(err.Error(), "permission denied") {
				t.Errorf("%s: failing %q gave %v", driver, read, err)
			}
		}
	}
}

func TestReadCanonSchemaRejectsNoSessionAndUnknownDriver(t *testing.T) {
	if _, err := ReadCanonSchema(context.Background(), nil, "postgres", "public"); err == nil || err.Error() != "not connected" {
		t.Errorf("nil session: %v", err)
	}
	_, err := ReadCanonSchema(context.Background(), &catalogSession{}, "oracle", "x")
	if err == nil || !strings.Contains(err.Error(), "does not support oracle") {
		t.Errorf("unknown driver: %v", err)
	}
}

// MySQL foreign keys (multi-column), FULLTEXT and HASH indexes,
// expression index parts, views without the database name, and
// routines with their parameters.
func TestReadCanonSchemaMySQLKeysViewsRoutines(t *testing.T) {
	s := &catalogSession{answers: map[string][][]Cell{
		"information_schema.columns": {
			cells("orders", "id", "int", "NO", "<null>", "", "int"),
			cells("orders", "a", "int", "NO", "NULL", "", "int"),
			cells("orders", "b", "int", "YES", "1+1", "DEFAULT_GENERATED", "int"),
			cells("orders", "body", "text", "YES", "<null>", "", "text"),
			cells("users", "id", "int", "NO", "<null>", "", "int"),
		},
		"information_schema.table_constraints tc\nJOIN": {
			cells("orders", "fk_ab", "FOREIGN KEY", "a", "users", "id", "CASCADE", "NO ACTION"),
			cells("orders", "fk_ab", "FOREIGN KEY", "b", "users", "id2", "CASCADE", "NO ACTION"),
			cells("ghost", "PRIMARY", "PRIMARY KEY", "id", "<null>", "<null>", "<null>", "<null>"),
		},
		"information_schema.check_constraints": {
			cells("ghost", "c1", "(x > 0)"),
		},
		"information_schema.statistics": {
			cells("orders", "ft", "1", "body", "FULLTEXT", "<null>"),
			cells("orders", "h", "1", "a", "HASH", "<null>"),
			cells("orders", "fx", "1", "<null>", "BTREE", "<null>"),
			cells("ghost", "g", "1", "id", "BTREE", "<null>"),
		},
		"information_schema.views": {
			cells("v_orders", "select `app`.`orders`.`id` AS `id` from `app`.`orders`"),
		},
		"information_schema.routines": {
			cells("add_one", "FUNCTION", "INT", "RETURN x + 1", "add_one"),
			cells("noop", "PROCEDURE", "<null>", "BEGIN END", "noop"),
		},
		"information_schema.parameters": {
			cells("add_one", "<null>", "x", "INT"),
			cells("noop", "IN", "a", "INT"),
			cells("noop", "OUT", "b", "VARCHAR(10)"),
		},
	}}
	got, err := ReadCanonSchema(context.Background(), s, "mysql", "app")
	if err != nil {
		t.Fatal(err)
	}
	if len(got.Tables) != 2 {
		t.Fatalf("tables: %+v", got.Tables)
	}
	o := got.Tables[0]
	if o.Columns[1].Default != "" || o.Columns[2].Default != "(1+1)" {
		t.Errorf("defaults: NULL must be none, an expression default wrapped: %+v", o.Columns)
	}
	want := CanonConstraint{Kind: "FOREIGN KEY", Name: "fk_ab", Columns: []string{"a", "b"}, RefTable: "users", RefColumns: []string{"id", "id2"}, OnUpdate: "CASCADE"}
	if len(o.Constraints) != 1 || !reflect.DeepEqual(o.Constraints[0], want) {
		t.Errorf("fk: %+v", o.Constraints)
	}
	if len(got.Tables[1].Constraints) != 0 {
		t.Errorf("constraints of unknown tables leaked: %+v", got.Tables[1])
	}
	byName := map[string]CanonIndex{}
	for _, ix := range o.Indexes {
		byName[ix.Name] = ix
	}
	if byName["ft"].Method != "FULLTEXT" || byName["h"].Method != "HASH" || byName["fx"].Exprs[0] != "(expression)" {
		t.Errorf("indexes: %+v", o.Indexes)
	}
	if len(got.Views) != 1 || strings.Contains(got.Views[0].Definition, "`app`.") {
		t.Errorf("view keeps the database name: %+v", got.Views)
	}
	if len(got.Routines) != 2 {
		t.Fatalf("routines: %+v", got.Routines)
	}
	if r := got.Routines[0]; r.Kind != "FUNCTION" || r.Args != "`x` int" || r.Returns != "int" || r.Language != "SQL" {
		t.Errorf("function: %+v", r)
	}
	if r := got.Routines[1]; r.Kind != "PROCEDURE" || r.Args != "IN `a` int, OUT `b` varchar(10)" {
		t.Errorf("procedure: %+v", r)
	}
}

func TestMySQLRuleTreatsNoActionAndRestrictAsDefault(t *testing.T) {
	for in, want := range map[string]string{"NO ACTION": "", " restrict ": "", "cascade": "CASCADE", "SET NULL": "SET NULL", "": ""} {
		if got := mysqlRule(in); got != want {
			t.Errorf("mysqlRule(%q) = %q, want %q", in, got, want)
		}
	}
}

func TestStripSchemaPrefixKeepsOtherNames(t *testing.T) {
	q := PostgresDialect{}.QuoteIdent
	if got := stripSchemaPrefix("SELECT public.a, xpublic.b, \"public\".c", "public", q); got != "SELECT a, xpublic.b, c" {
		t.Errorf("plain: %q", got)
	}
	if got := stripSchemaPrefix(`SELECT "My Schema".a, My Schema.b`, "My Schema", q); got != "SELECT a, My Schema.b" {
		t.Errorf("quoted-only schema: %q", got)
	}
	if got := stripSchemaPrefix("SELECT public.a", "", q); got != "SELECT public.a" {
		t.Errorf("no schema: %q", got)
	}
}

func TestListSchemasPerDriver(t *testing.T) {
	ctx := context.Background()
	pg := &catalogSession{answers: map[string][][]Cell{
		"current_database()": {cells("shop")},
		"FROM pg_namespace":  {cells("public"), cells("sales"), cells("")},
	}}
	db, schemas, err := ListSchemas(ctx, pg, "postgresql")
	if err != nil || db != "shop" || !reflect.DeepEqual(schemas, []string{"public", "sales"}) {
		t.Errorf("postgres: %q %v %v", db, schemas, err)
	}
	my := &catalogSession{answers: map[string][][]Cell{"information_schema.schemata": {cells("app"), cells("logs")}}}
	if db, schemas, err := ListSchemas(ctx, my, "mysql"); err != nil || db != "" || !reflect.DeepEqual(schemas, []string{"app", "logs"}) {
		t.Errorf("mysql: %q %v %v", db, schemas, err)
	}
	sq := &catalogSession{answers: map[string][][]Cell{"PRAGMA database_list": {cells("0", "main", "/x.db"), cells("1", "temp", ""), cells("2", "aux", "/y.db")}}}
	if _, schemas, err := ListSchemas(ctx, sq, "sqlite"); err != nil || !reflect.DeepEqual(schemas, []string{"main", "aux"}) {
		t.Errorf("sqlite (temp must be hidden): %v %v", schemas, err)
	}
	if _, _, err := ListSchemas(ctx, sq, "oracle"); err == nil || !strings.Contains(err.Error(), "does not support") {
		t.Errorf("unknown driver: %v", err)
	}
	if _, _, err := ListSchemas(ctx, &catalogSession{failOn: "current_database"}, "postgres"); err == nil {
		t.Error("postgres database name error was swallowed")
	}
	if _, _, err := ListSchemas(ctx, &catalogSession{failOn: "schemata"}, "mysql"); err == nil {
		t.Error("mysql list error was swallowed")
	}
}
